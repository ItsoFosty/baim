import { existsSync, readFileSync, writeFileSync } from "node:fs";

const sources = [
  "assets_src/chapter1/scenes/election_booth/layers.json",
  "assets_src/chapter1/scenes/archive/layers.json",
  "assets_src/chapter1/scenes/mayor_office/layers.json",
  "assets_src/chapter1/scenes/apartment/layers.json",
  "assets_src/chapter1/scenes/village_square/layers.json",
  "assets_src/chapter1/scenes/mehana/layers.json",
  "assets_src/chapter1/scenes/municipality/layers.json"
];
const outputPath = "src/content/chapter1/sceneLayers.generated.js";

const sceneLayerGeometry = {};

for (const sourcePath of sources) {
  if (!existsSync(sourcePath)) continue;
  const source = JSON.parse(readFileSync(sourcePath, "utf8"));
  if (!source.sceneId) throw new Error(`${sourcePath} sceneId is required`);
  sceneLayerGeometry[source.sceneId] = {
    sceneId: source.sceneId,
    foregroundLayers: (source.layers || [])
      .filter((layer) => layer.enabled !== false)
      .map((layer) => runtimeLayer(layer, sourcePath))
  };
}

writeFileSync(
  outputPath,
  `// Generated by tools/build-scene-layer-runtime.js. Edit assets_src scene layer sources instead.\nexport const sceneLayerGeometry = ${JSON.stringify(sceneLayerGeometry, null, 2)};\n`
);

function runtimeLayer(layer, sourcePath) {
  if (!layer.id) throw new Error(`${sourcePath} layer id is required`);
  if (!layer.asset) throw new Error(`${sourcePath} ${layer.id} asset is required`);
  if (!Number.isFinite(Number(layer.zIndex))) throw new Error(`${sourcePath} ${layer.id} zIndex must be a number`);
  const result = {
    id: layer.id,
    asset: layer.asset,
    zIndex: Number(layer.zIndex)
  };
  copyNumber(layer, result, "top");
  copyNumber(layer, result, "left");
  copyNumber(layer, result, "right");
  copyNumber(layer, result, "bottom");
  copyNumber(layer, result, "width");
  copyNumber(layer, result, "height");
  if (layer.visibleWhenFlag) result.visibleWhenFlag = String(layer.visibleWhenFlag);
  if (layer.requirements) result.requirements = layer.requirements;
  if (layer.visibleWhenTargetId) result.visibleWhenTargetId = String(layer.visibleWhenTargetId);
  if (layer.hiddenWhenFlag) result.hiddenWhenFlag = String(layer.hiddenWhenFlag);
  if (layer.hiddenWhenItemOwned) result.hiddenWhenItemOwned = String(layer.hiddenWhenItemOwned);
  if (layer.hiddenWhenState) result.hiddenWhenState = String(layer.hiddenWhenState);
  if (layer.animation) result.animation = runtimeAnimation(layer.animation, sourcePath, layer.id);
  if (layer.talkAnimation) {
    if (!layer.talkAnimation.npcId) throw new Error(`${sourcePath} ${layer.id} talkAnimation npcId is required`);
    result.talkAnimation = {
      ...runtimeAnimation(layer.talkAnimation, sourcePath, layer.id),
      npcId: String(layer.talkAnimation.npcId)
    };
  }
  if (layer.reactionAnimations) {
    result.reactionAnimations = Object.fromEntries(Object.entries(layer.reactionAnimations).map(([id, animation]) => {
      if (!animation.npcId || animation.loop !== false) {
        throw new Error(`${sourcePath} ${layer.id} reaction ${id} needs npcId and loop: false`);
      }
      return [id, { ...runtimeAnimation(animation, sourcePath, layer.id), npcId: String(animation.npcId) }];
    }));
  }
  if (layer.visibleDuringAction) {
    result.visibleDuringAction = {
      actionName: String(layer.visibleDuringAction.actionName || ""),
      fromFrame: Math.max(0, Math.floor(Number(layer.visibleDuringAction.fromFrame) || 0))
    };
  }
  if (!hasNumber(result, "top") && !hasNumber(result, "bottom")) result.top = 0;
  if (!hasNumber(result, "left") && !hasNumber(result, "right")) result.left = 0;
  return result;
}

function runtimeAnimation(animation, sourcePath, layerId) {
  const requiredPositiveNumbers = ["frameWidth", "frameHeight", "frameCount", "columns"];
  if (!animation.asset) throw new Error(`${sourcePath} ${layerId} animation asset is required`);
  for (const key of requiredPositiveNumbers) {
    if (!Number.isFinite(Number(animation[key])) || Number(animation[key]) <= 0) {
      throw new Error(`${sourcePath} ${layerId} animation ${key} must be a positive number`);
    }
  }
  const frameDurationMs = Number(animation.frameDurationMs);
  const fps = Number(animation.fps);
  if (!(frameDurationMs > 0) && !(fps > 0)) {
    throw new Error(`${sourcePath} ${layerId} animation needs frameDurationMs or fps`);
  }
  const bounds = animation.contentBounds;
  if (!bounds || !["x", "y", "w", "h"].every((key) => Number.isFinite(Number(bounds[key])))) {
    throw new Error(`${sourcePath} ${layerId} animation contentBounds must contain x, y, w, and h`);
  }
  if (Number(bounds.w) <= 0 || Number(bounds.h) <= 0) {
    throw new Error(`${sourcePath} ${layerId} animation contentBounds must have positive dimensions`);
  }
  const registration = animation.registrationBounds;
  if (registration && (!["x", "y", "w", "h"].every((key) => Number.isFinite(Number(registration[key])))
    || Number(registration.w) <= 0 || Number(registration.h) <= 0)) {
    throw new Error(`${sourcePath} ${layerId} animation registrationBounds must contain finite x, y and positive w, h`);
  }
  const phaseKeys = ["loopStartFrame", "loopEndFrame", "returnStartFrame"];
  const phases = {};
  for (const key of phaseKeys) if (animation[key] != null) {
    if (!Number.isInteger(animation[key]) || animation[key] < 0 || animation[key] >= Number(animation.frameCount)) {
      throw new Error(sourcePath + ' ' + layerId + ' ' + key + ' must be a valid frame index');
    }
    phases[key] = animation[key];
  }
  if (animation.loopEndFrame != null && animation.loopEndFrame < (animation.loopStartFrame || 0)) {
    throw new Error(sourcePath + ' ' + layerId + ' loop range is reversed');
  }
  if (animation.returnStartFrame != null && animation.returnStartFrame <= (animation.loopEndFrame ?? Number(animation.frameCount) - 1)) {
    throw new Error(sourcePath + ' ' + layerId + ' return must follow the speech loop');
  }
  return {
    ...phases,
    ...(registration ? { registrationBounds: Object.fromEntries(["x", "y", "w", "h"].map((key) => [key, Number(registration[key])])) } : {}),
    asset: String(animation.asset),
    frameWidth: Math.floor(Number(animation.frameWidth)),
    frameHeight: Math.floor(Number(animation.frameHeight)),
    frameCount: Math.floor(Number(animation.frameCount)),
    columns: Math.floor(Number(animation.columns)),
    ...(frameDurationMs > 0 ? { frameDurationMs } : { fps }),
    loop: animation.loop !== false,
    contentBounds: Object.fromEntries(["x", "y", "w", "h"].map((key) => [key, Number(bounds[key])]))
  };
}

function copyNumber(from, to, key) {
  if (Number.isFinite(Number(from[key]))) to[key] = Number(from[key]);
}

function hasNumber(value, key) {
  return Number.isFinite(Number(value[key]));
}
