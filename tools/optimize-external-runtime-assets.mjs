import { existsSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join } from "node:path";
import sharp from "sharp";
import { externalAnimationV1 as source } from "../src/content/art/externalAnimationV1.generated.js";

const SCALE = 0.5;
const GENERATED_MODULE = "src/content/art/externalAnimationRuntime.generated.js";
const REPORT_PATH = "target/external_animation_v1/reports/runtime-optimization-report.json";
const runtime = structuredClone(source);
const outputBySource = new Map();
const report = [];

for (const [key, metadata] of Object.entries(source.animations || {})) {
  if (!metadata?.src || !existsSync(metadata.src)) continue;
  const extension = extname(metadata.src);
  const output = join(dirname(metadata.src), `${basename(metadata.src, extension)}.webp`);
  const sourceStat = statSync(metadata.src);
  const outputCurrent = existsSync(output) && statSync(output).mtimeMs >= sourceStat.mtimeMs;
  if (!outputCurrent) {
    const image = sharp(metadata.src);
    const dimensions = await image.metadata();
    await image
      .resize({
        width: Math.max(1, Math.round(dimensions.width * SCALE)),
        height: Math.max(1, Math.round(dimensions.height * SCALE)),
        kernel: "lanczos3"
      })
      .webp({ quality: 88, alphaQuality: 95, effort: 4, smartSubsample: true })
      .toFile(output);
  }
  outputBySource.set(metadata.src, output.replaceAll("\\", "/"));
  report.push({
    key,
    source: metadata.src,
    output: output.replaceAll("\\", "/"),
    sourceBytes: sourceStat.size,
    outputBytes: statSync(output).size,
    scale: SCALE
  });
}

const optimized = transform(runtime);
writeFileSync(
  GENERATED_MODULE,
  `// Generated by tools/optimize-external-runtime-assets.mjs. Runtime-only optimized animation metadata.\nexport const externalAnimationV1 = ${JSON.stringify(optimized, null, 2)};\n`
);
writeFileSync(REPORT_PATH, `${JSON.stringify({ scale: SCALE, animations: report }, null, 2)}\n`);
console.log(JSON.stringify({
  animations: report.length,
  sourceMiB: mib(report.reduce((sum, item) => sum + item.sourceBytes, 0)),
  outputMiB: mib(report.reduce((sum, item) => sum + item.outputBytes, 0)),
  scale: SCALE
}, null, 2));

function transform(value) {
  if (Array.isArray(value)) return value.map(transform);
  if (!value || typeof value !== "object") {
    return typeof value === "string" && outputBySource.has(value) ? outputBySource.get(value) : value;
  }
  const result = {};
  const runtimeMetadata = typeof value.src === "string" && outputBySource.has(value.src);
  for (const [key, entry] of Object.entries(value)) {
    if (key === "src" && outputBySource.has(entry)) {
      result[key] = outputBySource.get(entry);
    } else if (runtimeMetadata && ["frameWidth", "frameHeight", "sheetWidth", "sheetHeight", "baselineY"].includes(key)) {
      result[key] = scaled(entry);
    } else if (runtimeMetadata && ["contentBounds", "sourceContentBounds"].includes(key)) {
      result[key] = scaledRect(entry);
    } else if (runtimeMetadata && ["frameRects", "sourceFrameRects", "frameContentBounds", "sourceFrameContentBounds"].includes(key)) {
      result[key] = entry.map(scaledRect);
    } else {
      result[key] = transform(entry);
    }
  }
  if (runtimeMetadata) {
    result.runtimeScale = SCALE;
    result.runtimeSource = "half-scale-alpha-webp";
  }
  return result;
}

function scaledRect(rect = {}) {
  return {
    ...rect,
    ...Object.fromEntries(["x", "y", "w", "h"]
      .filter((key) => Number.isFinite(Number(rect[key])))
      .map((key) => [key, scaled(rect[key])]))
  };
}

function scaled(value) {
  return Math.max(0, Math.round(Number(value) * SCALE));
}

function mib(bytes) {
  return Math.round((bytes / 1048576) * 100) / 100;
}
